// Golden wire vectors taken byte for byte from a real plugin/daemon session, so the
// test peer cannot drift from the plugin it stands in for. Nothing here was written by
// hand, and every label was read back out of the decoded fields rather than assumed
// from the order the messages were captured in.
//
// Provenance: the vectors were recorded from live sessions with the plugin's wire dump
// (SCORBIT_WIRE_DUMP). Tokens are replaced with synthetic ones. One vector from a
// recorded session is withheld from this public repository; it can be supplied through
// the SCORBIT_WIRE_VECTORS environment variable.
//
// Each vector is a complete wire frame: the u32 length prefix, then type, flags and
// seq, then the payload — the bytes as they crossed, so a vector can be written to a
// socket or handed to the decoder unchanged. Convert with ScorbitTest::Unhex.
//
// The .scap capture cannot supply any of these: it records at the IFrameSource seam,
// one layer above the socket, so it holds frame content but no message headers and no
// handshake. It does validate them — a decoded FRAME_REPLY_PIXELS payload is
// byte-identical to the matching seam frame once ReplayFrameSource unpacks it. Match on
// frame id, never on ordinal: the daemon re-requests while its since value is parked,
// so roughly twice as many frames cross the wire as reach the seam (SB-4695).

